const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { test } = require("node:test");

const checker = import("../scripts/check-ipc-allowlist.mjs");
const root = path.resolve(__dirname, "..");
const permission = `# Automatically generated - DO NOT EDIT!
[[permission]]
identifier = "allow-one"
description = "Allows one."
commands.allow = ["one"]
[[permission]]
identifier = "deny-one"
description = "Denies one."
commands.deny = ["one"]
`;

async function fixture(t) {
  const { checkIpcAllowlist, pluginPermissions } = await checker;
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "pocketstream-ipc-"));
  t.after(() => {
    // Only delete this test's allocated directory, after checking its resolved
    // parent. Do not follow an unexpected replacement/reparse target.
    assert.equal(path.dirname(fs.realpathSync(directory)), fs.realpathSync(os.tmpdir()));
    fs.rmSync(directory, { recursive: true });
  });
  const write = (name, source) => {
    const file = path.join(directory, name);
    fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, source);
  };
  const capability = { identifier: "default", local: true, windows: ["main"], permissions: ["allow-one", ...pluginPermissions] };
  write("tsconfig.json", JSON.stringify({ compilerOptions: { target: "ES2022", module: "ESNext", moduleResolution: "Bundler", skipLibCheck: true }, include: ["src/**/*.ts"] }));
  write("src-tauri/build.rs", 'const COMMANDS: &[&str] = &["one"];');
  write("src-tauri/src/lib.rs", `fn main() { tauri::Builder::default()
    .plugin(tauri_plugin_dialog::init())
    .plugin(tauri_plugin_notification::init())
    .plugin(tauri_plugin_updater::Builder::new().build())
    .invoke_handler(tauri::generate_handler![commands::one]); }`);
  write("src-tauri/capabilities/default.json", JSON.stringify(capability));
  write("src-tauri/permissions/autogenerated/one.toml", permission);
  const wrapper = 'const invoke = window.__TAURI__.core.invoke;\nexport async function one() { return invoke("one"); }\nexport function onEvent() {}\n';
  write("src/lib/tauri-api.ts", wrapper);
  write("src/main.ts", 'import * as api from "./lib/tauri-api"; api.one();');
  return { write, wrapper, capability, check: () => checkIpcAllowlist(directory, { expectedCount: 1 }).errors };
}

test("production inventories agree on 46 commands and referenced wrappers", async () => {
  const result = (await checker).checkIpcAllowlist(root);
  assert.deepEqual(result.errors, []);
  assert.equal(result.commands.length, 46); assert.equal(result.wrapperCount, 46);
});

test("symbol-resolved named imports, namespace aliases, const function aliases and callback values count", async t => {
  const f = await fixture(t);
  for (const source of [
    'import { one as renamed } from "./lib/tauri-api"; renamed();',
    'import * as api from "./lib/tauri-api"; const first = api; const second = first; second.one();',
    'import * as api from "./lib/tauri-api"; const first = api.one; const second = first; setTimeout(second, 0);',
    'import { one } from "./lib/tauri-api"; setTimeout(one, 0);',
    'import * as api from "./lib/tauri-api"; setTimeout(api.one, 0);',
  ]) {
    f.write("src/main.ts", source); assert.deepEqual(f.check(), [], source);
  }
});

test("comments, unused imports, declarations, shadowed names and type-only uses do not count", async t => {
  const f = await fixture(t);
  f.write("src/unused.d.ts", 'import { one } from "./lib/tauri-api"; type Ignored = typeof one;');
  for (const source of [
    '// api.one();\nimport { one } from "./lib/tauri-api";',
    'import * as api from "./lib/tauri-api"; type Only = typeof api.one;',
    'import { one } from "./lib/tauri-api"; function unrelated(one: () => void) { one(); }',
    'import * as api from "./lib/tauri-api"; const unusedAlias = api.one;',
    'import type { one } from "./lib/tauri-api"; type Only = typeof one;',
  ]) {
    f.write("src/main.ts", source); assert(f.check().some(x => x.includes("unreferenced exported command wrapper")), source);
  }
});

const drift = [
  ["registrations", f => f.write("src-tauri/src/lib.rs", "tauri::generate_handler![commands::unexpected];"), "generate_handler!"],
  ["COMMANDS", f => f.write("src-tauri/build.rs", 'const COMMANDS: &[&str] = &["unexpected"];'), "generate_handler!"],
  ["capability application permission", f => { f.capability.permissions[0] = "allow-unexpected"; f.write("src-tauri/capabilities/default.json", JSON.stringify(f.capability)); }, "main capability"],
  ["wrapper command", f => f.write("src/lib/tauri-api.ts", f.wrapper.replace('invoke("one")', 'invoke("unexpected")')), "not in COMMANDS"],
  ["generated filename", f => f.write("src-tauri/permissions/autogenerated/stale.toml", permission), "permission files"],
  ["generated allow payload", f => f.write("src-tauri/permissions/autogenerated/one.toml", permission.replace('commands.allow = ["one"]', 'commands.allow = ["unexpected"]')), "exact allow"],
  ["generated deny payload", f => f.write("src-tauri/permissions/autogenerated/one.toml", permission.replace('commands.deny = ["one"]', 'commands.deny = []')), "exact deny"],
  ["generated identifier", f => f.write("src-tauri/permissions/autogenerated/one.toml", permission.replace("deny-one", "deny-unexpected")), "exact deny"],
  ["extra permission payload", f => f.write("src-tauri/permissions/autogenerated/one.toml", permission + 'commands.allow = ["one"]\n'), "exact deny"],
  ["custom permission file", f => f.write("src-tauri/permissions/extra.toml", permission), "permission files"],
  ["plugin permission", f => { f.capability.permissions.push("core:default"); f.write("src-tauri/capabilities/default.json", JSON.stringify(f.capability)); }, "main capability"],
  ["remote origin", f => { f.capability.remote = { urls: ["https://example.com"] }; f.write("src-tauri/capabilities/default.json", JSON.stringify(f.capability)); }, "local main"],
  ["extra capability", f => f.write("src-tauri/capabilities/extra.json", JSON.stringify(f.capability)), "capability files"],
  ["duplicate registration", f => f.write("src-tauri/src/lib.rs", "tauri::generate_handler![commands::one, commands::one];"), "duplicate"],
  ["duplicate COMMANDS", f => f.write("src-tauri/build.rs", 'const COMMANDS: &[&str] = &["one", "one"];'), "expected 1 commands"],
  ["commented registration", f => f.write("src-tauri/src/lib.rs", "// tauri::generate_handler![commands::one];"), "expected one"],
  ["string registration", f => f.write("src-tauri/src/lib.rs", 'let text = "tauri::generate_handler![commands::one]";'), "expected one"],
];
for (const [name, seed, expected] of drift) {
  test(`independent ${name} drift fails`, async t => {
    const f = await fixture(t); assert.deepEqual(f.check(), []); seed(f);
    assert(f.check().some(x => x.includes(expected)), `${name}: ${f.check().join("\n")}`);
  });
}

test("computed access, escaped namespaces and unresolved wrapper indirection fail with a location", async t => {
  const f = await fixture(t);
  for (const source of [
    'const key = "one"; api[key]();', 'api["one"]();', 'register(api);',
    'const { one } = api; one();', 'let alias = api; alias.one();',
    'let alias = api.one; alias();', 'api.one.bind(null)();', 'api.missing();',
  ]) {
    f.write("src/main.ts", 'import * as api from "./lib/tauri-api"; ' + source);
    assert(f.check().some(x => /src[\\/]main.ts:1:\d+:/.test(x)), source);
  }
});

test("dynamic commands and escaped invoke references are rejected", async t => {
  const f = await fixture(t);
  for (const source of [
    f.wrapper.replace('invoke("one")', 'invoke(command)'),
    f.wrapper.replace('invoke("one")', 'invoke(`one`)'),
    f.wrapper + '\nconst escaped = invoke; escaped("one");',
    f.wrapper + '\nregister(invoke);',
    f.wrapper + '\nwindow.__TAURI__.core.invoke("one");',
  ]) {
    f.write("src/lib/tauri-api.ts", source); assert(f.check().some(x => x.includes("invoke")), source);
  }
});

test("raw invocation outside wrappers fails, including global and import aliases", async t => {
  const f = await fixture(t);
  for (const source of [
    'window.__TAURI__.core.invoke("one");',
    'const core = window.__TAURI__.core; const { invoke: escaped } = core; escaped("one");',
    'window.__TAURI_INTERNALS__.invoke("one");',
    'import { invoke as escaped } from "@tauri-apps/api/core"; escaped("one");',
  ]) {
    f.write("src/main.ts", 'import * as api from "./lib/tauri-api"; api.one();\n' + source);
    assert(f.check().some(x => x.includes("invoke")), source);
  }
});
